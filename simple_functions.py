
def add(a,b):
    return a+b

def to_positive(a):
    if a > 0:
        return a
    else:
        return a * -1

def is_even(a):
    return a % 2 == 0

def is_odd(a):
    return a % 2 == 1

def divide(a,b):
    # if b == 0:
    #     return "ERROR"
    return a/b

def multiply(a,b):
    return a*b

def power(a,b):
    return a**b




